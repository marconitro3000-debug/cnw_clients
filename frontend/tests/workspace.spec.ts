import {test,expect} from '@playwright/test'

test('companies group their contacts and news and saved clients keep portfolio state on reload',async({page})=>{
  const initialPortfolio=await (await page.request.post('/api/portfolios',{data:{name:'Cartera inicial de la prueba'}})).json()
  await page.request.post('/api/portfolios/'+initialPortfolio.uuid+'/default')
  const people=[]
  for(const [name,company,link] of [['Clara Empresa Nueva QA','Gestora Empresas Nueva QA','clara-empresa-nueva-qa'],['Mario Empresa Nueva QA','Gestora Empresas Nueva QA',''],['Clara Otra Empresa QA','Gestora Empresas Nueva QA Partners','clara-otra-empresa-qa']]){
    const r=await page.request.post('/api/contacts',{data:{name,company,role:'CIO',country:'España',linkedin_url:link?'https://linkedin.com/in/'+link:null,note:'Fixture empresarial'}})
    expect(r.ok(),await r.text()).toBeTruthy();people.push(await r.json())
  }
  await page.goto('/')
  await expect(page.locator('.sidebar').getByRole('button',{name:'Subsectores',exact:true})).toHaveCount(0)
  await expect(page.locator('.sidebar').getByRole('button',{name:'Noticias',exact:true})).toHaveCount(0)
  await page.locator('.sidebar').getByRole('button',{name:'Mis clientes',exact:true}).click()
  await page.getByLabel('Nombre de tu cartera').fill('Marco QA')
  await page.getByRole('button',{name:'Crear cartera',exact:true}).click()
  await page.getByRole('button',{name:'Usar como predeterminada',exact:true}).click()
  await expect(page.getByLabel('Cartera activa')).toContainText('Marco QA · Predeterminada')
  await page.getByLabel('Nombre de tu cartera').fill('Equipo QA')
  await page.getByRole('button',{name:'Crear cartera',exact:true}).click()
  await page.reload()
  const portfolios=await (await page.request.get('/api/portfolios')).json()
  await expect(page.getByLabel('Cartera activa')).toHaveValue(portfolios.items.find((p:any)=>p.name==='Marco QA').uuid)
  await page.getByLabel('Cartera activa').selectOption(portfolios.items.find((p:any)=>p.name==='Equipo QA').uuid)
  await page.getByRole('button',{name:'Usar como predeterminada',exact:true}).click()
  await expect(page.getByRole('button',{name:'Cartera predeterminada',exact:true})).toBeDisabled()
  await page.reload()
  await expect(page.getByLabel('Cartera activa')).toContainText('Equipo QA · Predeterminada')
  await page.locator('.sidebar').getByRole('button',{name:'Empresas',exact:true}).click()
  await page.getByLabel('Buscar empresa').fill('Gestora Empresas Nueva QA')
  const company=page.getByRole('button',{name:'Abrir empresa Gestora Empresas Nueva QA',exact:true})
  await expect(company).toContainText('2 contactos')
  await page.screenshot({path:'test-results/screenshots/companies-desktop.png',fullPage:true})
  await company.click()
  await expect(page).toHaveURL(/#\/empresas\/[a-f0-9-]+/)
  await expect(page.locator('.contact-table tbody tr')).toHaveCount(2)
  await expect(page.locator('.contact-table tbody')).not.toContainText('Clara Otra Empresa QA')
  const row=page.locator('.contact-table tbody tr').filter({hasText:'Clara Empresa Nueva QA'})
  await row.getByRole('button',{name:'Guardar en Equipo QA · Clara Empresa Nueva QA',exact:true}).click()
  await expect(row.getByRole('button',{name:'Guardado en Equipo QA · Clara Empresa Nueva QA',exact:true})).toBeVisible()
  await page.reload()
  await expect(page.locator('.contact-table tbody tr')).toHaveCount(2)
  await page.screenshot({path:'test-results/screenshots/company-contacts-desktop.png',fullPage:true})
  const newsRequests:string[]=[]
  await page.route('**/api/signals?*',route=>{const url=new URL(route.request().url());newsRequests.push(url.searchParams.get('firm_id')||'');return route.fulfill({json:{items:[],total:0}})})
  await page.getByRole('tab',{name:/Noticias de la empresa/}).click()
  await expect(page.getByRole('heading',{name:'Noticias y publicaciones recientes'})).toBeVisible()
  await expect.poll(()=>newsRequests).toContain(String(people[0].firm_id))
  expect(newsRequests.every(id=>id===String(people[0].firm_id))).toBe(true)
  await page.locator('.sidebar').getByRole('button',{name:'Mis clientes',exact:true}).click()
  const client=page.locator('.client-record').filter({hasText:'Clara Empresa Nueva QA'})
  await expect(client).toBeVisible()
  await client.getByLabel('Estado de Clara Empresa Nueva QA').selectOption('viewed')
  await client.getByLabel('Siguiente paso').fill('Preparar ejemplo de earnings')
  await client.getByLabel('Notas de cartera').fill('He revisado la carta trimestral; falta hablar con ella.')
  await client.getByLabel('Fecha de seguimiento').fill('2026-11-05')
  await client.getByRole('button',{name:'Guardar seguimiento',exact:true}).click()
  await expect(client.getByRole('button',{name:'Guardar seguimiento',exact:true})).toBeEnabled()
  await page.reload()
  await expect(client.getByLabel('Estado de Clara Empresa Nueva QA')).toHaveValue('viewed')
  await expect(client.getByLabel('Notas de cartera')).toHaveValue('He revisado la carta trimestral; falta hablar con ella.')
  await expect(client.getByLabel('Siguiente paso')).toHaveValue('Preparar ejemplo de earnings')
  expect(await (await page.request.get('/api/crm/contacts/'+people[0].id+'/interactions')).json()).toHaveLength(0)
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.screenshot({path:'test-results/screenshots/portfolio-mobile.png',fullPage:true})
})

test('initial consultative scripts are bilingual and personalisation is required before copying',async({page})=>{
  const created=await page.request.post('/api/contacts',{data:{name:'Clara Guion Consultivo QA',company:'Gestora Guion Consultivo QA',role:'CIO',country:'España',linkedin_url:'https://linkedin.com/in/clara-guion-consultivo-qa',note:'Fixture de guion'}})
  expect(created.ok()).toBeTruthy()
  await page.goto('/#/guiones')
  await expect(page.getByRole('region',{name:'Método de venta consultiva'})).toBeVisible()
  const card=page.locator('.script-card').filter({hasText:'01 · Gestor fundamental'})
  await expect(card).toContainText('Soy {asesor}, de Kerna')
  await page.getByLabel('Idioma de los guiones').selectOption('en')
  await expect(card).toContainText('from Kerna')
  await page.goto('/#/contactos')
  await page.getByLabel('Buscar en agenda').fill('Clara Guion Consultivo QA')
  await page.getByRole('button',{name:'Registrar mensaje a Clara Guion Consultivo QA',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'Ficha de Clara Guion Consultivo QA'})
  await dialog.getByRole('tab',{name:'Registrar interacción',exact:true}).click()
  const scripts=await (await page.request.get('/api/scripts')).json()
  await dialog.getByLabel(/Guion utilizado/).selectOption(scripts.find((s:any)=>s.title==='01 · Gestor fundamental').uuid)
  await expect(dialog.getByRole('button',{name:'Copiar apertura',exact:true})).toBeDisabled()
  await dialog.getByLabel('Estrategia o enfoque público').fill('renta variable europea')
  await expect(dialog.locator('.script-preview')).toContainText('Hola Clara')
  await expect(dialog.locator('.script-preview')).toContainText('renta variable europea')
  await expect(dialog.getByRole('button',{name:'Copiar apertura',exact:true})).toBeEnabled()
  await dialog.getByLabel('Idioma del mensaje').selectOption('en')
  await expect(dialog.locator('.script-preview')).toContainText('Hi Clara')
  await page.screenshot({path:'test-results/screenshots/consultative-script.png',fullPage:true})
})