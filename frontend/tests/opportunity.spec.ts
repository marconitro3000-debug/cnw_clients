import { test, expect } from '@playwright/test'

test('qualification answers set the commercial opportunity without changing fit',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  const created=await page.request.post('/api/contacts',{data:{name:'Olga Oportunidad QA',company:'Gestora Oportunidad QA',role:'CIO',country:'España',employees_min:25,employees_max:25,equity:true,linkedin_url:'https://linkedin.com/in/opportunity-qa',note:'Fixture de oportunidad'}})
  const contact=await created.json()
  await page.goto('/')
  await page.locator('.sidebar').getByRole('button',{name:/^Contactos/}).click()
  await page.getByLabel('Buscar en agenda').fill('Olga Oportunidad QA')
  const row=page.locator('.contact-table tbody tr').filter({hasText:'Olga Oportunidad QA'})
  await expect(row).toContainText('Oportunidad 0/100 · Sin cualificar')
  await row.getByRole('button',{name:'Añadir comentario a Olga Oportunidad QA'}).click()
  const dialog=page.getByRole('dialog',{name:'Ficha de Olga Oportunidad QA'})
  const panel=dialog.getByRole('region',{name:'Oportunidad comercial'})
  await panel.getByRole('group',{name:/^P3/}).getByRole('button',{name:'Sí',exact:true}).click()
  await expect(panel).toContainText('25/100 · Sin cualificar')
  await panel.getByRole('group',{name:/^P6/}).getByRole('button',{name:'Sí',exact:true}).click()
  await panel.getByRole('group',{name:/^P4/}).getByRole('button',{name:'Sí',exact:true}).click()
  await expect(panel).toContainText('60/100 · Cliente objetivo')
  await expect(panel.getByRole('group',{name:/^P4/}).getByRole('button',{name:'Sí',exact:true})).toHaveAttribute('aria-pressed','true')
  await dialog.getByRole('button',{name:'Cerrar ventana'}).click()
  await expect(row).toContainText('Oportunidad 60/100 · Cliente objetivo')
  await page.getByRole('button',{name:'Más filtros',exact:true}).click()
  await page.getByLabel('Oportunidad comercial').selectOption('unwilling')
  await expect(row).toHaveCount(0)
  await page.getByLabel('Oportunidad comercial').selectOption('target')
  await expect(row).toHaveCount(1)
  await page.getByLabel('Orden de agenda').selectOption('opportunity')
  await expect(page.locator('.pagination')).toContainText('mayor oportunidad primero')
  const saved=await (await page.request.get('/api/contacts/'+contact.id)).json()
  expect(saved.qualification.change).toBe('yes')
  expect(saved.score).toBe(contact.score)
  expect(errors).toEqual([])
})
