  await page.route('**/api/scanning',route=>route.fulfill({json:scans}))
  await page.route('**/api/scanning/web/stop',route=>{scans.web.enabled=false;scans.web.status='stopped';running=false;return route.fulfill({json:scans})})
  await page.route('**/api/scanning/public/stop',route=>{scans.public.enabled=false;scans.public.status='stopped';return route.fulfill({json:scans})})
