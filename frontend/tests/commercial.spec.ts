  const scans:any={web:{enabled:true,status:'running',reason:'',lots:2,last_run_id:99},public:{enabled:true,status:'queued',reason:'',lots:1,last_run_id:null},apollo:{enabled:false,status:'idle',reason:'',lots:0,last_run_id:null}}
  let running=true
  const run={id:99,keywords:'equity',provider:'web',status:'running',completed_queries:1,total_queries:8,credits:1,contacts_found:0,errors:[],queries:[],started_at:'2026-10-07T10:00:00Z',finished_at:null}
