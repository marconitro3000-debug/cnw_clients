test('Spain shortcut is visible and filters both the agenda and the exported CSV',async({page})=>{
  for(const [name,country,suffix] of [['Geografia QA Madrid','España','es'],['Geografia QA Paris','Francia','fr'],['Geografia QA Pendiente','','unknown']] as const){
    const r=await page.request.post('/api/contacts',{data:{name,company:'Gestora Geografia '+suffix,role:'CIO',country,linkedin_url:'https://linkedin.com/in/geografia-qa-'+suffix,note:'Fixture de país'}})
    expect(r.ok(),await r.text()).toBeTruthy()
  }
  await page.goto('/#/contactos')
  await page.getByLabel('Buscar en agenda').fill('Geografia QA')
  await expect(page.locator('.contact-table tbody tr')).toHaveCount(3)
  await expect(page.getByLabel('País de agenda')).toBeVisible()
  const shortcut=page.getByRole('button',{name:'Solo España',exact:true})
  await shortcut.click()
  await expect(shortcut).toHaveAttribute('aria-pressed','true')
  await expect(page.getByLabel('País de agenda')).toHaveValue('España')
  await expect(page.locator('.contact-table tbody tr')).toHaveCount(1)
  await expect(page.locator('.contact-table tbody')).toContainText('Geografia QA Madrid')
  const href=await page.getByRole('link',{name:'Exportar lista filtrada'}).getAttribute('href')
  const csv=await (await page.request.get(href!)).text()
  expect(csv).toContain('Geografia QA Madrid')
  expect(csv).not.toContain('Geografia QA Paris')
  expect(csv).not.toContain('Geografia QA Pendiente')
  await shortcut.click()
  await expect(page.locator('.contact-table tbody tr')).toHaveCount(3)
  await page.getByLabel('País de agenda').selectOption('Francia')
  await expect(shortcut).toHaveAttribute('aria-pressed','false')
  await expect(page.locator('.contact-table tbody tr')).toHaveCount(1)
  await expect(page.locator('.contact-table tbody')).toContainText('Geografia QA Paris')
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await shortcut.click()
  await expect(page.locator('.contact-table tbody')).toContainText('Geografia QA Madrid')
  await page.screenshot({path:'test-results/screenshots/spain-filter-mobile.png',fullPage:true})
})