import {test,expect} from '@playwright/test'

test('pages are independent, routes survive refresh and script actions never launch searches',async({page})=>{
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Evolución comercial'})).toBeVisible()
  await expect(page.locator('.crm-workspace')).toHaveCount(0)
  await page.locator('.sidebar').getByRole('button',{name:'Guiones',exact:true}).click()
  await expect(page).toHaveURL(/#\/guiones$/)
  await expect(page.getByRole('heading',{level:1})).toHaveText('Guiones comerciales.')
  await expect(page.getByRole('button',{name:'Nuevo guion',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:/Nueva búsqueda/})).toHaveCount(0)
  await expect(page.getByRole('heading',{name:'Evolución comercial'})).toHaveCount(0)
  await expect(page.locator('.stats-grid')).toHaveCount(0)
  await expect(page.locator('h1')).toHaveCSS('color','rgb(17, 17, 17)')
  await page.reload()
  await expect(page.getByRole('heading',{level:1})).toHaveText('Guiones comerciales.')
  await page.locator('.sidebar').getByRole('button',{name:/^Contactos/}).click()
  await expect(page.getByRole('heading',{name:'Tu lista permanente'})).toBeVisible()
  await expect(page.locator('.scan-controls')).toHaveCount(0)
  await page.goBack()
  await expect(page.getByRole('heading',{level:1})).toHaveText('Guiones comerciales.')
  await page.locator('.sidebar').getByRole('button',{name:'Actividad',exact:true}).click()
  await expect(page).toHaveURL(/#\/actividad$/)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button',{name:/Nueva búsqueda/})).toHaveCount(0)
  await page.locator('.sidebar').getByRole('button',{name:'Ajustes',exact:true}).click()
  await page.getByRole('tab',{name:'Modelo local',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Modelo local de Hugging Face'})).toBeVisible()
  await expect(page.getByRole('checkbox',{name:/IA local/})).toHaveCount(0)
  await page.screenshot({path:'test-results/screenshots/settings-page.png',fullPage:true})
})

test('search defaults are simple and the model requires no per-search switch',async({page})=>{
  await page.goto('/#/busquedas')
  await page.getByRole('button',{name:'Nueva búsqueda web',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'Nueva búsqueda',exact:true})
  await expect(dialog.getByLabel('Consultas de gestoras')).toHaveCount(0)
  await expect(dialog.getByRole('checkbox')).toHaveCount(1)
  await expect(dialog.getByRole('checkbox')).toBeChecked()
  await expect(dialog.getByLabel('Palabras clave')).toHaveCSS('color','rgb(17, 17, 17)')
  const box=await dialog.getByRole('checkbox').boundingBox()
  expect(box?.width).toBe(18)
  await dialog.getByLabel('Palabras clave').fill('small cap equities')
  await dialog.getByRole('button',{name:'Opciones avanzadas',exact:true}).click()
  await expect(dialog.getByLabel('Consultas de gestoras')).toHaveValue(/small cap equities/)
  await dialog.getByRole('button',{name:'Ocultar opciones avanzadas',exact:true}).click()
  await expect(dialog.getByLabel('Consultas de gestoras')).toHaveCount(0)
  await page.screenshot({path:'test-results/screenshots/simple-search.png',fullPage:true})
  await page.keyboard.press('Escape')
  await page.getByRole('tab',{name:'Apollo',exact:true}).click()
  await expect(page.getByRole('button',{name:'Buscar en Apollo'})).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.screenshot({path:'test-results/screenshots/searches-page.png',fullPage:true})
})
