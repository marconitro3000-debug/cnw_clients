import {test,expect} from '@playwright/test'

test('news has its own tab, dated sources, reviews and the same contact agenda',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  const response=await page.request.post('/api/contacts',{data:{name:'Ana Noticias QA',company:'Aurora Noticias QA',role:'CIO',linkedin_url:'https://linkedin.com/in/news-qa',note:'Equipo QA'}})
  const c=await response.json()
  const source='https://aurora.example/news/fund'
  const fresh:any={uuid:'news-ui-1',firm_uuid:c.firm_uuid,firm_id:c.firm_id,company:c.company,domain:'aurora.example',kind:'fund_launch',label:'Nuevo fondo o estrategia',title:'Aurora amplía su equipo y lanza un fondo',quote:'Aurora Noticias QA launches a new equity fund.',source_url:source,published_at:'2026-10-09',event_at:null,date_basis:'document',observed_at:'2026-10-09T09:00:00Z',method:'rules',review:'detected',recency:'recent',reviews:[]}
  const unknown:any={...fresh,uuid:'news-ui-2',kind:'event_driven',label:'Estrategia event-driven',title:'Estrategia de inversión',quote:'Aurora Noticias QA follows an event-driven strategy.',published_at:null,date_basis:'unknown',recency:'undated'}
  const scans:any={web:{enabled:true,status:'running',lots:1},public:{enabled:false,status:'idle',lots:0},signals:{enabled:false,status:'idle',lots:0},apollo:{enabled:false,status:'idle',lots:0}}
  let starts=0,paid=0
  await page.route('**/api/health',async route=>{const r=await route.fetch();return route.fulfill({json:{...await r.json(),api_configured:true}})})
  await page.route('**/api/searches/latest',route=>route.fulfill({json:null}))
  await page.route('**/api/scanning',route=>route.fulfill({json:scans}))
  await page.route('**/api/apollo/enrich',route=>{paid++;return route.fulfill({status:400,json:{detail:'No se enriquece'}})})
  await page.route('**/api/signals/targets',route=>route.fulfill({json:{firms:[{id:c.firm_id,name:c.company,domain:'aurora.example'}],kinds:{fund_launch:fresh.label,event_driven:unknown.label}}}))
  await page.route('**/api/signals?*',route=>{const u=new URL(route.request().url());const include=u.searchParams.get('recent_only')==='false';const rows=[fresh,...include?[unknown]:[]].filter(s=>(!u.searchParams.get('kind')||s.kind===u.searchParams.get('kind'))&&(include||s.review!=='rejected'));return route.fulfill({json:{items:rows,total:rows.length}})})
  await page.route('**/api/signals/searches',route=>{starts++;expect(route.request().postDataJSON()).toEqual({days:90,firm_ids:[],continuous:true});scans.signals={enabled:true,status:'queued',lots:0};return route.fulfill({status:202,json:scans})})
  await page.route('**/api/signals/news-ui-1/review',route=>{const decision=route.request().postDataJSON().decision;fresh.review=decision;fresh.reviews.push({decision,author:'Marco',at:'2026-10-09T10:00:00Z'});return route.fulfill({json:fresh})})
  const decorated=()=>({...c,business_signals:[fresh,unknown],recent_signal_count:fresh.review==='rejected'?0:1})
  await page.route('**/api/crm/contacts?*',route=>{const u=new URL(route.request().url());const match=!u.searchParams.get('q')||c.company.includes(u.searchParams.get('q')!);return route.fulfill({json:{items:match?[decorated()]:[],total:match?1:0}})})
  await page.route('**/api/contacts/'+c.id,route=>route.fulfill({json:decorated()}))
  await page.goto('/#/busquedas')
  await expect(page.locator('.scan-card')).toHaveCount(3)
  await page.getByRole('tab',{name:'Noticias y señales',exact:true}).click()
  await expect(page.locator('.signals-workspace')).toBeVisible()
  await expect(page.locator('.public-data-workspace')).toHaveCount(0)
  await expect(page.locator('.crm-workspace')).toHaveCount(0)
  const card=page.locator('.signal-card').filter({hasText:'Aurora amplía'})
  await expect(card.locator('blockquote')).toHaveText(fresh.quote)
  await expect(card.getByRole('link',{name:'Leer publicación original'})).toHaveAttribute('href',source)
  await expect(card.getByRole('link',{name:'Leer publicación original'})).toHaveAttribute('target','_blank')
  await expect(page.locator('.signal-card')).toHaveCount(1)
  await page.getByRole('button',{name:'Buscar noticias y posts',exact:true}).last().click()
  await expect(page.getByText('En cola: empezará al terminar el lote activo.')).toBeVisible()
  await expect(page.getByRole('button',{name:'Detener noticias',exact:true})).toBeVisible()
  await card.getByRole('button',{name:'Confirmar señal'}).click()
  await expect(card.getByText('Confirmada',{exact:true})).toBeVisible()
  await card.getByText('Historial de revisión').click()
  await expect(card.locator('.signal-reviews')).toContainText('Marco')
  await page.getByRole('checkbox',{name:'Incluir antiguas y sin fecha'}).check()
  await expect(page.locator('.signal-card')).toHaveCount(2)
  const event=page.locator('.signal-card').filter({hasText:'Estrategia de inversión'})
  await expect(event).toContainText('Sin fecha fiable')
  await expect(event).toContainText('No es una señal de intención de compra.')
  await page.screenshot({path:'test-results/screenshots/news-signals.png',fullPage:true})
  await card.getByRole('button',{name:'Ver contactos'}).click()
  await expect(page).toHaveURL(/#\/contactos/)
  await expect(page.getByLabel('Buscar en agenda')).toHaveValue(c.company)
  const row=page.locator('.contact-table tbody tr').filter({hasText:c.name})
  await expect(row).toContainText('1 señales recientes')
  await page.getByRole('button',{name:'Más filtros',exact:true}).click()
  await page.getByLabel('Señales de la gestora').selectOption('recent')
  await expect(page.getByRole('link',{name:'Exportar lista filtrada'})).toHaveAttribute('href',/signals=recent/)
  await row.getByRole('button',{name:'Registrar llamada a '+c.name}).click()
  const dialog=page.getByRole('dialog',{name:'Ficha de '+c.name})
  await expect(dialog.getByRole('heading',{name:'Noticias y señales de la gestora'})).toBeVisible()
  await dialog.getByText('Nuevo fondo o estrategia · 9/10/2026',{exact:true}).click()
  await expect(dialog.getByRole('link',{name:'Leer publicación original'}).first()).toHaveAttribute('href',source)
  expect(await (await page.request.get('/api/crm/contacts/'+c.id+'/interactions')).json()).toHaveLength(0)
  await page.screenshot({path:'test-results/screenshots/news-contact.png',fullPage:true})
  expect(starts).toBe(1);expect(paid).toBe(0);expect(errors).toEqual([])
})

test('news workspace and scanner cards fit a narrow screen',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('/#/busquedas')
  await page.getByRole('tab',{name:'Noticias y señales',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Noticias y publicaciones recientes'})).toBeVisible()
  await expect(page.locator('.scan-card')).toHaveCount(3)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  const color=await page.getByRole('heading',{name:'Noticias y publicaciones recientes'}).evaluate(el=>getComputedStyle(el).color)
  expect(['rgb(0, 0, 0)','rgb(17, 17, 17)']).toContain(color)
  await page.screenshot({path:'test-results/screenshots/news-mobile.png',fullPage:true})
})
