import { test, expect } from '@playwright/test'

test('scanned firms are grouped by subsector, can be moved and open the agenda',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.request.post('/api/contacts',{data:{name:'Quentin Sector QA',company:'Sector Quant QA',role:'Head of quantitative research',country:'España',employees_min:20,employees_max:20,equity:true,linkedin_url:'https://linkedin.com/in/sector-quant-qa',note:'Fixture de subsector'}})
  await page.goto('/')
  await page.locator('.sidebar').getByRole('button',{name:'Subsectores',exact:true}).click()
  await expect(page).toHaveURL(/#\/subsectores/)
  await page.getByRole('tab',{name:/Cuantitativa y quantamental/}).click()
  const detail=page.getByRole('region',{name:'Gestoras de Cuantitativa y quantamental'})
  const firm=detail.locator('.segment-firm').filter({hasText:'Sector Quant QA'})
  await expect(firm).toBeVisible()
  await expect(firm.getByRole('link',{name:/Quentin Sector QA/})).toHaveAttribute('href','https://www.linkedin.com/in/sector-quant-qa/')
  await firm.getByText('Ver por qué').click()
  await expect(firm.locator('blockquote')).toContainText('quantitative')
  await firm.getByLabel('Subsector de Sector Quant QA').selectOption('hedge_fund')
  await page.getByRole('tab',{name:/Hedge funds/}).click()
  const moved=page.getByRole('region',{name:'Gestoras de Hedge funds y retorno absoluto'}).locator('.segment-firm').filter({hasText:'Sector Quant QA'})
  await expect(moved).toContainText('Asignado a mano')
  await page.getByRole('region',{name:'Gestoras de Hedge funds y retorno absoluto'}).getByRole('button',{name:/^Ver sus/}).click()
  await expect(page).toHaveURL(/#\/contactos/)
  const row=page.locator('.contact-table tbody tr').filter({hasText:'Quentin Sector QA'})
  await expect(row).toContainText('Hedge funds y retorno absoluto')
  await page.reload()
  await page.locator('.sidebar').getByRole('button',{name:'Subsectores',exact:true}).click()
  await page.getByRole('tab',{name:/Hedge funds/}).click()
  await moved.getByLabel('Subsector de Sector Quant QA').selectOption('')
  await page.getByRole('tab',{name:/Cuantitativa y quantamental/}).click()
  await expect(detail.locator('.segment-firm').filter({hasText:'Sector Quant QA'})).toBeVisible()
  await page.getByRole('button',{name:'Cambiar a modo oscuro'}).click()
  await page.reload()
  expect(await page.evaluate(()=>document.documentElement.dataset.theme)).toBe('dark')
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
