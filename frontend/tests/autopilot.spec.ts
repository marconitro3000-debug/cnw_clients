import { test, expect } from '@playwright/test'

test('autopilot panel, news page and contacts hidden by Qwen can be restored',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  const created=await page.request.post('/api/contacts',{data:{name:'Hugo Oculto QA',company:'Gestora Oculta QA',role:'CIO',country:'España',equity:true,linkedin_url:'https://linkedin.com/in/hidden-qa',note:'Fixture oculta'}})
  const contact=await created.json()
  await page.request.put('/api/crm/contacts/'+contact.id+'/quality',{data:{status:'junk'}})
  await page.goto('/')
  const panel=page.getByRole('region',{name:'Piloto automático'})
  await expect(panel).toBeVisible()
  await expect(panel.getByRole('button',{name:'Activar piloto automático'})).toBeVisible()
  await page.locator('.sidebar').getByRole('button',{name:'Noticias',exact:true}).click()
  await expect(page).toHaveURL(/#\/noticias/)
  await expect(page.getByRole('heading',{name:/Noticias y señales/})).toBeVisible()
  await page.locator('.sidebar').getByRole('button',{name:/^Contactos/}).click()
  await page.getByLabel('Buscar en agenda').fill('Hugo Oculto QA')
  const row=page.locator('.contact-table tbody tr').filter({hasText:'Hugo Oculto QA'})
  await expect(row).toHaveCount(0)
  await page.getByRole('button',{name:'Ocultados por Qwen',exact:true}).click()
  await page.getByLabel('Datos de contacto disponibles').selectOption('all')
  await expect(row).toContainText('Oculto')
  await row.getByRole('button',{name:'No es basura · restaurar'}).click()
  await expect(row).toHaveCount(0)
  await page.getByRole('button',{name:'Todos',exact:true}).click()
  await expect(row).toHaveCount(1)
  expect(errors).toEqual([])
})
