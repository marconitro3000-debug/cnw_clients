import {test,expect} from '@playwright/test'

test('Kerna branding and clean settings tabs retain usable forms on desktop and mobile',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/#/configuracion')
  await expect(page).toHaveTitle('Kerna Client Research')
  await expect(page.getByRole('link',{name:'Kerna Client Research, inicio'})).toBeVisible()
  await expect(page.getByRole('heading',{level:1})).toHaveText('Ajustes.')
  await expect(page.getByRole('tab',{name:'Conexiones',exact:true})).toHaveAttribute('aria-selected','true')
  await expect(page.getByRole('heading',{name:'Tavily',exact:true})).toBeVisible()
  const input=page.locator('.settings-page').getByLabel('API key de Tavily')
  const rect=await input.boundingBox();expect(rect?.height).toBeGreaterThanOrEqual(44);expect(rect?.width).toBeGreaterThan(250)
  await expect(page.getByRole('button',{name:'Guardar Apollo',exact:true})).toBeDisabled()
  await expect(page.getByLabel('Presupuesto gratuito por ciclo')).not.toBeVisible()
  await expect(page.getByLabel('Tu nombre para las interacciones')).toHaveCount(0)
  await expect(page.getByRole('heading',{name:'Modelo local de Hugging Face'})).toHaveCount(0)
  await page.screenshot({path:'test-results/screenshots/kerna-settings-connections.png',fullPage:true})
  await page.getByRole('tab',{name:'Mi perfil',exact:true}).click()
  await expect(page.getByLabel('Tu nombre para las interacciones')).toBeVisible()
  await expect(page.getByLabel('API key de Tavily')).toHaveCount(0)
  await page.getByRole('tab',{name:'Datos e historial',exact:true}).click()
  await expect(page.getByRole('link',{name:'Descargar contactos CSV'})).toHaveAttribute('href','/api/crm/contacts/export?status=all')
  await page.getByRole('tab',{name:'Modelo local',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Modelo local de Hugging Face'})).toBeVisible()
  await page.setViewportSize({width:390,height:844})
  await page.getByRole('tab',{name:'Conexiones',exact:true}).click()
  await expect(input).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.screenshot({path:'test-results/screenshots/kerna-settings-mobile.png',fullPage:true})
  expect(errors).toEqual([])
})

test('Apollo hides empty candidate tables and never displays a web search as its result',async({page})=>{
  const webRun={id:902,provider:'web',keywords:'renta variable',status:'completed',completed_queries:3,total_queries:3,credits:3,contacts_found:3,new_contacts:3,review_contacts:3,errors:[],queries:[],started_at:'2026-10-07T10:00:00Z',finished_at:'2026-10-07T10:01:00Z'}
  await page.route('**/api/searches/latest',route=>route.fulfill({json:webRun}))
  await page.route('**/api/search-history',route=>route.fulfill({json:[webRun]}))
  await page.goto('/#/busquedas')
  await expect(page.locator('.last-run')).toContainText('3 contactos')
  await page.getByRole('tab',{name:'Apollo',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Candidatos encontrados'})).toHaveCount(0)
  await expect(page.getByText('0 candidatos',{exact:false})).toHaveCount(0)
  await expect(page.getByRole('button',{name:/Incorporar.*seleccionados/})).toHaveCount(0)
  await expect(page.locator('.last-run')).toHaveCount(0)
  await expect(page.locator('.scan-summary')).toHaveCount(0)
  await page.screenshot({path:'test-results/screenshots/kerna-apollo-empty.png',fullPage:true})
  await page.unroute('**/api/search-history')
  await page.route('**/api/search-history',route=>route.fulfill({json:[{...webRun,id:903,provider:'apollo',mode:'discover',candidates:[],contacts_found:0}]}))
  await page.reload()
  await page.getByRole('tab',{name:'Apollo',exact:true}).click()
  await expect(page.locator('.apollo-search-status')).toContainText('Esta búsqueda de Apollo')
  await expect(page.getByRole('heading',{name:'Candidatos encontrados'})).toHaveCount(0)
})
