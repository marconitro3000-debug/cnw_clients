import {test,expect} from '@playwright/test'

test('score, reachable profiles and information-first call and email actions',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  const created=await page.request.post('/api/contacts',{data:{name:'Ana Canales QA',company:'Aurora Canales QA',role:'CIO',linkedin_url:'https://linkedin.com/in/channels-qa',photo_url:'https://media.licdn.com/channels-qa.jpg',note:'Fuente comprobada QA'}})
  const c=await created.json()
  await page.request.patch('/api/crm/contacts/'+c.id,{data:{owner:'Marco',email:'ana@aurora.example',phone:'+34 600 111 222'}})
  await page.request.post('/api/contacts',{data:{name:'Ana Incompleta QA',company:'Aurora Incompleta QA',role:'CIO',note:'Sin canales publicados'}})
  const other=await page.request.post('/api/contacts',{data:{name:'Ana Web QA',company:'Aurora Web QA',role:'CIO',note:'Fuente web'}})
  await page.request.patch('/api/crm/contacts/'+(await other.json()).id,{data:{email:'web@aurora.example'}})
  await page.route('https://media.licdn.com/**',route=>route.abort())
  await page.goto('/#/contactos')
  await page.getByLabel('Buscar en agenda').fill('Ana')
  const row=page.locator('.contact-table tbody tr').filter({hasText:'Ana Canales QA'})
  await expect(row).toHaveCount(1)
  await expect(page.locator('.contact-table')).not.toContainText('Ana Incompleta QA')
  await expect(row.getByRole('link',{name:'Perfil de LinkedIn ↗'})).toHaveAttribute('href','https://www.linkedin.com/in/channels-qa/')
  await expect(row.locator('.avatar')).toContainText('AC')
  const web=page.locator('.contact-table tbody tr').filter({hasText:'Ana Web QA'})
  await expect(web).toContainText('Fuente web · sin LinkedIn')
  await expect(web.getByRole('link',{name:/LinkedIn/})).toHaveCount(0)
  await page.getByLabel('Puntuación mínima',{exact:true}).fill('80')
  await expect(row).toHaveCount(0)
  const href=await page.getByRole('link',{name:'Exportar lista filtrada'}).getAttribute('href')
  expect(href).toContain('min_score=80');expect(href).toContain('reachability=reachable')
  await page.getByLabel('Puntuación mínima',{exact:true}).fill('0')
  await page.getByLabel('Datos de contacto disponibles').selectOption('missing')
  await expect(page.locator('.contact-table')).toContainText('Ana Incompleta QA')
  await expect(row).toHaveCount(0)
  await page.getByLabel('Datos de contacto disponibles').selectOption('reachable')
  await row.getByRole('button',{name:'Registrar llamada a Ana Canales QA'}).click()
  const dialog=page.getByRole('dialog',{name:'Ficha de Ana Canales QA'})
  await expect(dialog.getByRole('tab',{name:'Información',exact:true})).toHaveAttribute('aria-selected','true')
  await expect(dialog.getByRole('link',{name:'ana@aurora.example'})).toHaveAttribute('href','mailto:ana@aurora.example')
  await expect(dialog.getByRole('link',{name:'+34 600 111 222'})).toHaveAttribute('href','tel:+34 600 111 222')
  await expect(dialog.getByRole('link',{name:'Abrir perfil de Ana Canales QA ↗'})).toHaveAttribute('target','_blank')
  await expect(dialog).toContainText('Foto: LinkedIn.')
  expect(await (await page.request.get('/api/crm/contacts/'+c.id+'/interactions')).json()).toHaveLength(0)
  await page.screenshot({path:'test-results/screenshots/contact-information.png',fullPage:true})
  await dialog.getByRole('button',{name:'Cerrar ventana'}).click()
  await row.getByRole('button',{name:'Ver correo de Ana Canales QA'}).click()
  await expect(dialog.getByRole('tab',{name:'Información',exact:true})).toHaveAttribute('aria-selected','true')
  await dialog.getByRole('button',{name:'Registrar correo',exact:true}).click()
  await expect(dialog.getByRole('button',{name:'Correo',exact:true})).toHaveAttribute('aria-pressed','true')
  await dialog.getByLabel('Comentario de interacción').fill('Correo registrado después de revisar los datos.')
  await dialog.getByRole('button',{name:'Guardar interacción',exact:true}).click()
  await dialog.getByRole('tab',{name:'Historial',exact:true}).click()
  await expect(dialog.locator('.timeline')).toContainText('Correo registrado después')
  const events=await (await page.request.get('/api/crm/contacts/'+c.id+'/interactions')).json()
  expect(events).toHaveLength(1);expect(events[0].channel).toBe('email')
  await dialog.getByRole('button',{name:'Cerrar ventana'}).click()
  await page.reload()
  await page.getByLabel('Buscar en agenda').fill('Ana Canales QA')
  await expect(row).toContainText('Contactado')
  await page.screenshot({path:'test-results/screenshots/contact-channels.png',fullPage:true})
  expect(errors).toEqual([])
})

test('public contact scan queues behind discovery without keys or enrichment requests',async({page})=>{
  let starts=0,paid=0
  const scans:any={web:{enabled:true,status:'running',reason:'',lots:1},public:{enabled:false,status:'idle',reason:'',lots:0},apollo:{enabled:false,status:'idle',reason:'',lots:0}}
  await page.route('**/api/scanning',route=>route.fulfill({json:scans}))
  await page.route('**/api/apollo/enrich',route=>{paid++;return route.fulfill({status:400,json:{detail:'No autorizado en esta prueba'}})})
  await page.route('**/api/public/searches',route=>{starts++;expect(route.request().postDataJSON()).toEqual({continuous:true});scans.public={enabled:true,status:'queued',reason:'',lots:0};return route.fulfill({status:202,json:scans})})
  await page.goto('/#/busquedas')
  await page.getByRole('tab',{name:'Datos de contacto',exact:true}).click()
  await expect(page.locator('.public-data-workspace input[type=password]')).toHaveCount(0)
  await page.getByRole('button',{name:'Buscar datos de contacto',exact:true}).click()
  await expect(page.getByText('En cola: empezará al terminar el lote activo.')).toBeVisible()
  await expect(page.getByRole('button',{name:'Detener web',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Detener datos',exact:true})).toBeVisible()
  expect(starts).toBe(1);expect(paid).toBe(0)
  await page.screenshot({path:'test-results/screenshots/public-contact-scan.png',fullPage:true})
})
