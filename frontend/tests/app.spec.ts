test('active search can be stopped and quota notices are visible', async ({ page }) => {
  const run = { id: 99, keywords: 'equity', status: 'running', completed_queries: 2, total_queries: 8, credits: 2, contacts_found: 0, errors: [] as string[], started_at: '2026-10-07T10:00:00Z', finished_at: null, queries: [] }
  let canceled = false
  await page.route('**/api/searches/latest', route => route.fulfill({ json: canceled ? { ...run, status: 'stopped' } : run }))
  await page.route('**/api/searches/99/cancel', route => {
    canceled = true
    return route.fulfill({ json: { ...run, status: 'stopped' } })
  })
  await page.goto('/')
  await page.locator('.sidebar').getByRole('button',{name:'Búsquedas',exact:true}).click()
  await expect(page.getByText('Buscando oportunidades')).toBeVisible()
  await page.getByRole('button', { name: 'Detener', exact: true }).click()
  await expect(page.getByText(/Última búsqueda: Detenida/)).toBeVisible()
  await page.unroute('**/api/searches/latest')
  await page.route('**/api/searches/latest', route => route.fulfill({ json: { ...run, status: 'quota_exhausted', errors: ['Tavily ha agotado la cuota. Se conservan los resultados parciales.'] } }))
  await page.reload()
  await page.getByRole('button', { name: 'Ver actividad', exact: true }).click()
  await expect(page.getByText('Tavily ha agotado la cuota. Se conservan los resultados parciales.')).toBeVisible()
})


test('connect from search, keep edited queries and enable search immediately', async ({ page }) => {
  let configured = false
  let started = false
  const health = () => ({ ok: true, api_configured: configured, credits_used: 0, monthly_limit: 1000, countries: ['España'] })
  await page.route('**/api/health', route => route.fulfill({ json: health() }))
  await page.route('**/api/settings/tavily', route => {
    expect(route.request().postDataJSON()).toEqual({ api_key: 'tvly-test-inline-configuration' })
    configured = true
    return route.fulfill({ json: health() })
  })
  await page.route('**/api/searches', route => {
    const body = route.request().postDataJSON()
    expect(body.continuous).toBe(true)
    expect(body.queries.some((q: { text: string }) => q.text === 'site:linkedin.com/in/ "{gestora}" CIO custom')).toBe(true)
    started = true
    return route.fulfill({ status: 202, json: { id: 101, keywords: body.keywords, status: 'completed', completed_queries: 0, total_queries: 0, credits: 0, contacts_found: 0, errors: [], queries: [], started_at: '2026-10-07T10:00:00Z', finished_at: '2026-10-07T10:00:00Z' } })
  })
  await page.goto('/')
  await page.locator('.sidebar').getByRole('button',{name:'Búsquedas',exact:true}).click()
  await page.getByRole('button', { name: 'Nueva búsqueda web', exact: true }).click()
  await page.getByRole('button',{name:'Opciones avanzadas',exact:true}).click()
  const dialog = page.getByRole('dialog', { name: 'Nueva búsqueda' })
  await expect(dialog.getByRole('button', { name: 'Iniciar búsqueda' })).toBeDisabled()
  await expect(dialog.getByLabel('Consultas de gestoras')).toHaveValue(/renta variable/)
  await dialog.getByLabel('Consultas de decisores').fill('site:linkedin.com/in/ "{gestora}" CIO custom')
  await dialog.getByLabel('API key de Tavily').fill('tvly-test-inline-configuration')
  await expect(dialog.getByLabel('API key de Tavily')).toHaveAttribute('type', 'password')
  await dialog.getByRole('button', { name: 'Guardar y conectar' }).click()
  await expect(dialog.getByRole('button', { name: 'Iniciar búsqueda' })).toBeEnabled()
  await expect(dialog.getByLabel('API key de Tavily')).toHaveCount(0)
  await expect(dialog.getByLabel('Consultas de decisores')).toHaveValue('site:linkedin.com/in/ "{gestora}" CIO custom')
  await dialog.getByRole('button', { name: 'Iniciar búsqueda' }).click()
  await expect(dialog).toHaveCount(0)
  expect(started).toBe(true)
})

test('configuration reports errors and clears the key after saving', async ({ page }) => {
  let configured = false
  const health = () => ({ ok: true, api_configured: configured, credits_used: 0, monthly_limit: 1000, countries: ['España'] })
  await page.route('**/api/health', route => route.fulfill({ json: health() }))
  await page.route('**/api/settings/tavily', route => {
    if (route.request().postDataJSON().api_key === 'incorrect') return route.fulfill({ status: 400, json: { detail: 'Pega la API key completa de Tavily, que empieza por tvly-.' } })
    configured = true
    return route.fulfill({ json: health() })
  })
  await page.goto('/')
  await page.getByRole('button', { name: 'Ayuda y configuración' }).click()
  const dialog = page.locator('.settings-page')
  await dialog.getByLabel('API key de Tavily').fill('incorrect')
  await dialog.getByRole('button', { name: 'Guardar y conectar' }).click()
  await expect(dialog.getByRole('alert')).toContainText('empieza por tvly-')
  await dialog.getByLabel('API key de Tavily').fill('tvly-test-settings-configuration')
  await dialog.getByRole('button', { name: 'Guardar y conectar' }).click()
  await expect(dialog.getByRole('status')).toHaveText('Clave guardada. Ya puedes iniciar una búsqueda.')
  await expect(dialog.getByLabel('API key de Tavily')).toHaveValue('')
  await expect(dialog.getByRole('button',{name:'Guardar y conectar'})).toBeDisabled()
})
